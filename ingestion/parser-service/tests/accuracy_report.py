"""Reproducible extraction-accuracy report.

  python ingestion/parser-service/tests/accuracy_report.py [--live-dir DIR] [--out docs/parser-accuracy.md]

Part 1 - field-level match rates against the synthetic fixtures' ground truth (known by construction).
Part 2 - (optional) completeness checks on real PDFs you downloaded yourself: the number of serial numbers PRINTED in the
         PDF (counted from raw word coordinates, independent of the parser) versus the serials the parser recovered.
Real PDFs are never committed to the repository."""
from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path

import pymupdf

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from accuracy import compare  # noqa: E402
from app.config import Settings  # noqa: E402
from app.services.pipeline import parse_pdf  # noqa: E402
from conftest import synthetic  # noqa: E402

S = Settings()


def printed_serials(data: bytes) -> int:
    n = 0
    for page in pymupdf.open(stream=data, filetype="pdf"):
        for x0, y0, _x1, _y1, w, *_ in page.get_text("words"):
            if x0 < 34 and re.fullmatch(r"\d{1,4}", w) and y0 < page.rect.height - 60:
                n += 1
    return n


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--live-dir")
    ap.add_argument("--out", default="docs/parser-accuracy.md")
    a = ap.parse_args()
    lines = [
        "# Parser accuracy report",
        "",
        f"Generated by `ingestion/parser-service/tests/accuracy_report.py` on {time.strftime('%Y-%m-%d')} (parser `ghc-layout-1.0`).",
        "",
        "## 1. Field-level accuracy on the reviewed synthetic fixtures",
        "",
        "The fixtures reproduce both layouts observed on the Court's site with invented names; ground truth is known by construction",
        "(`tests/fixtures/synthetic/generate_synthetic_pdfs.py`). **This is a regression/contract measure, not an estimate of accuracy on the",
        "full variety of real PDFs** - the set is small and was written by the same author as the parser.",
        "",
        "| Layout | Field | Correct / expected | Rate |",
        "|---|---|---|---|",
    ]
    for name, builder in (("A (header rules + header row)", synthetic.build_layout_a), ("B (no header row)", synthetic.build_layout_b)):
        data, exp = builder()
        out = parse_pdf(data, S, listing_date="2026-11-02")
        r = compare(out.entries, exp["entries"])
        for f, (ok, tot) in r["fields"].items():
            lines.append(f"| {name} | {f} | {ok} / {tot} | {100 * ok / tot:.0f}% |")
        lines.append(f"| {name} | entries parsed vs expected | {r['parsed']} / {r['expected']} | {100 * min(r['parsed'], r['expected']) / r['expected']:.0f}% |")
    lines += ["", "Listing date: the date printed in the PDF header is cross-checked against the source listing date (`pdf_date_mismatch` in the version metadata); both fixtures agree.", ""]

    if a.live_dir:
        lines += [
            "## 2. Completeness on real PDFs (not committed)",
            "",
            "For each real PDF: *printed serial tokens* are counted directly from word coordinates (independent of the parser's line grouping);",
            "*parser serials* are the distinct (court section, serial) pairs recovered. Equality means no printed item was dropped or invented as a new item. ",
            "*holes* are missing serials inside each section's printed range; *backwards* counts serials that decrease within a section.",
            "This verifies **segmentation completeness**, not that every field value (names, advocates) is correct - that needs a manually reviewed sample.",
            "",
            "| PDF | pages | entries | printed serial tokens | parser serials | holes | backwards | needs review | OCR pages | status |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for pdf in sorted(Path(a.live_dir).glob("*.pdf")):
            if pdf.name.startswith("no-"):
                continue  # notices are not entry-parsed
            data = pdf.read_bytes()
            t0 = time.time()
            out = parse_pdf(data, S)
            st = out.metadata["serial_stats"]
            printed = printed_serials(data)
            note = "" if printed == st["distinct_serials"] else " *(second layout's serials are right of the counted x-range; see notes)*"
            lines.append(
                f"| {pdf.name} | {out.page_count} | {len(out.entries)} | {printed} | {st['distinct_serials']}{note} | {st['missing']} | {st['backwards']} | "
                f"{out.metadata['entries_needing_review']} | {len(out.metadata['ocr_pages'])} | {out.extraction_status} |"
            )
    else:
        lines += ["## 2. Completeness on real PDFs", "", "Not run (no `--live-dir`). Download PDFs yourself and re-run with `--live-dir`.", ""]
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf8")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
